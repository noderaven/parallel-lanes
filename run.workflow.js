// Quote a string for a POSIX shell (single quotes, embedded ones escaped).
function shellQuote(s) {
  return "'" + String(s).split("'").join("'\\''") + "'";
}

// A non-empty string (an agent-reported sha, for instance).
function present(v) {
  return typeof v === 'string' && v.length > 0;
}

// Rules every agent gets, task and phase alike.
function agentRules() {
  return [
    'Never amend, rebase, reset, or force-update a branch. Decline commit-message findings with a reason; ' +
      'they are reported to the user.',
    'Do not invoke parallel-lanes or any plan-execution skill.',
    'Combine independent shell commands into one call (with && or ;) when no command depends on reading the ' +
      "previous one's output: every separate call costs a full turn.",
  ].join('\n');
}

// How an agent stays in its checkout: the session running the workflow may
// sit in another checkout of the same repo, and agents start there.
function checkoutRules(dir, branch) {
  const q = shellQuote(dir);
  return [
    'Your shell may start in another checkout of this repo, so never rely on the current directory:',
    `- every shell command starts with cd ${q} && or uses git -C ${q};`,
    `- every project file path you read or write is absolute under ${dir} (the plan, spec, brief, report,`,
    '  review, and ledger files named here are the only paths outside it);',
    `- before each commit, check that git -C ${q} rev-parse --abbrev-ref HEAD prints ${branch}; if it does not,`,
    '  do not commit: stop and report it.',
  ].join('\n');
}

// For agents in the feature checkout (the user's main checkout in git mode).
// The project's setup commands are exempt: they may recreate ignored files
// (npm ci replaces node_modules) and are part of the run.
function keepFilesRule() {
  return 'Never run git clean -x or git clean -X, and never delete ignored or untracked files: they may hold ' +
    "the user's .env files, local databases, or credentials. Exempt from this: the project's own setup commands " +
    '(for example npm ci recreating node_modules), which may replace ignored files; run them as given.';
}

// Top-level manifest keys that must be present (manifest.schema.json lists
// the same keys as its top-level "required").
function manifestRequiredKeys() {
  return [
    'version', 'run_id', 'plan', 'spec', 'commit_rules', 'repo', 'commands',
    'prelude', 'lanes', 'join', 'hooks', 'limits', 'dry_run', 'done',
    'reviewed', 'sp_dir', 'skill_dir',
  ];
}

// run_id becomes part of branch names; lane ids become ledger file names
// (scripts/ledger enforces the same lane rule). manifest.schema.json repeats
// both patterns.
function runIdPattern() {
  return '^[a-z0-9-]+$';
}

function laneIdPattern() {
  return '^[A-Za-z0-9_][A-Za-z0-9._-]*$';
}

// Task ids name brief, report and review files in the ledger dir, so they
// must be safe file names (no '/', no leading '.' or '-'): the same pattern
// as lane ids. scripts/_brief.py, task-brief, start-task, finish-task and
// derive-lanes enforce it too; manifest.schema.json repeats it.
function taskIdPattern() {
  return laneIdPattern();
}

// A project-relative file path, normalized: '.' and empty segments dropped,
// '..' resolved. Returns null for an absolute path or one that leaves the
// project.
function normalizePath(path) {
  if (typeof path !== 'string' || path.length === 0 || path.startsWith('/')) return null;
  const out = [];
  for (const part of path.split('/')) {
    if (part === '' || part === '.') continue;
    if (part === '..') {
      if (out.length === 0) return null;
      out.pop();
    } else {
      out.push(part);
    }
  }
  return out.length > 0 ? out.join('/') : null;
}

// agent_type names a custom agent definition (scripts/find-agent-type prints
// it); manifest.schema.json repeats the pattern.
function agentTypePattern() {
  return '^[a-z0-9-]+$';
}

// Validate a run manifest. Returns a list of error messages; empty means
// valid. This function is authoritative; manifest.schema.json documents it.
function validateManifest(m) {
  const errors = [];
  const err = (msg) => errors.push(msg);
  const isObject = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
  const isText = (v) => typeof v === 'string' && v.length > 0;
  const isTextOrNull = (v) => v === null || isText(v);
  const isTextList = (v) => Array.isArray(v) && v.every(isText);
  const isPositiveInt = (v) => Number.isInteger(v) && v >= 1;
  const isAbsolutePath = (v) => isText(v) && v.startsWith('/');

  if (!isObject(m)) return ['manifest: must be an object'];

  for (const key of manifestRequiredKeys()) {
    if (!(key in m)) err(`${key}: missing`);
  }

  if ('version' in m && m.version !== 1) err('version: must be 1');
  for (const key of ['run_id', 'plan', 'commit_rules', 'skill_dir']) {
    if (key in m && !isText(m[key])) err(`${key}: must be a non-empty string`);
  }
  if (isText(m.run_id) && !new RegExp(runIdPattern()).test(m.run_id)) {
    err('run_id: must use only a-z, 0-9 and - (it becomes part of branch names)');
  }
  for (const key of ['spec', 'sp_dir']) {
    if (key in m && !isTextOrNull(m[key])) err(`${key}: must be a non-empty string or null`);
  }
  if ('agent_type' in m && m.agent_type !== null
    && !(typeof m.agent_type === 'string' && new RegExp(agentTypePattern()).test(m.agent_type))) {
    err(`agent_type: must be null or a name matching ${agentTypePattern()}`);
  }
  if ('dry_run' in m && typeof m.dry_run !== 'boolean') err('dry_run: must be a boolean');
  if ('autonomy' in m && m.autonomy !== 'autonomous' && m.autonomy !== 'supervised') {
    err("autonomy: must be 'autonomous' or 'supervised'");
  }
  if ('profile' in m && m.profile !== 'lite' && m.profile !== 'full') err("profile: must be 'lite' or 'full'");

  if ('repo' in m) {
    const repo = m.repo;
    if (!isObject(repo)) {
      err('repo: must be an object');
    } else {
      if (repo.mode !== 'git' && repo.mode !== 'shadow') err("repo.mode: must be 'git' or 'shadow'");
      for (const key of ['root', 'base_ref', 'branch', 'worktree_root', 'ledger_dir']) {
        if (!isText(repo[key])) err(`repo.${key}: must be a non-empty string`);
      }
      if (!isTextOrNull(repo.git_dir)) err('repo.git_dir: must be a non-empty string or null');
      if (repo.mode === 'shadow' && !isText(repo.git_dir)) err('repo.git_dir: required when repo.mode is shadow');
      if (isText(repo.branch) && repo.branch === repo.base_ref) err('repo.branch: must differ from repo.base_ref');
    }
  }

  const checkCommands = (where, cmds, allRequired) => {
    if (!isObject(cmds)) {
      err(`${where}: must be an object`);
      return;
    }
    const names = ['setup', 'test', 'lint', 'build'];
    for (const name of names) {
      if (name in cmds) {
        if (!isTextList(cmds[name])) err(`${where}.${name}: must be a list of non-empty strings`);
      } else if (allRequired) {
        err(`${where}.${name}: missing`);
      }
    }
    for (const name of Object.keys(cmds)) {
      if (!names.includes(name)) err(`${where}.${name}: unknown command group`);
    }
  };
  if ('commands' in m) checkCommands('commands', m.commands, true);

  // Tasks: shape, tier/security and batch rules, and id uniqueness across
  // all groups. allTasks collects every task object for the profile rules.
  const taskIds = new Set();
  const allTasks = [];
  const checkTask = (where, t) => {
    if (!isObject(t)) {
      err(`${where}: must be an object`);
      return;
    }
    allTasks.push(t);
    const name = isText(t.id) ? `task ${t.id}` : where;
    if (!isText(t.id)) err(`${where}.id: must be a non-empty string`);
    else if (!new RegExp(taskIdPattern()).test(t.id)) {
      err(`${where}.id: task id ${JSON.stringify(t.id)} must match ${taskIdPattern()} (it names files)`);
    } else if (taskIds.has(t.id)) err(`task ${t.id}: id appears more than once`);
    else taskIds.add(t.id);
    if (!isText(t.title)) err(`${name}: title must be a non-empty string`);
    if (!isTextList(t.files)) err(`${name}: files must be a list of non-empty strings`);
    else {
      for (const f of t.files) {
        if (normalizePath(f) === null) err(`${name}: file ${JSON.stringify(f)} is absolute or leaves the project`);
      }
    }
    if ('depends_on' in t) {
      const ok = Array.isArray(t.depends_on) && t.depends_on.every((d) => isObject(d) && isText(d.id)
        && (d.kind === 'code' || d.kind === 'contract'));
      if (!ok) err(`${name}: depends_on must be a list of {id, kind: 'code' or 'contract'}`);
    }
    if (t.tier !== 'standard' && t.tier !== 'sonnet' && t.tier !== 'light') {
      err(`${name}: tier must be 'standard', 'sonnet' or 'light'`);
    }
    if (typeof t.security !== 'boolean') err(`${name}: security must be a boolean`);
    if ((t.tier === 'sonnet' || t.tier === 'light') && t.security === true) {
      err(`${name}: a ${t.tier} tier task cannot have security set (security tasks are always standard)`);
    }
    if ('batch' in t) {
      if (!isText(t.batch)) err(`${name}: batch must be a non-empty string`);
      else if (t.tier !== 'light') err(`${name}: batch is allowed only on a light tier task`);
    }
  };
  const checkTaskList = (where, list) => {
    if (!Array.isArray(list)) {
      err(`${where}: must be a list`);
      return;
    }
    list.forEach((t, i) => checkTask(`${where}[${i}]`, t));
  };

  if ('prelude' in m) checkTaskList('prelude', m.prelude);

  // Deliberate overlaps: a file two lanes both change, with the tasks, why,
  // and the task whose version wins at the merge. Keyed by the normalized,
  // lower-cased path (a case-insensitive file system makes 'A.js' and 'a.js'
  // one file).
  const fileKey = (f) => (normalizePath(f) || f).toLowerCase();
  const overlapFor = new Map();
  if ('overlaps' in m) {
    if (!Array.isArray(m.overlaps)) {
      err('overlaps: must be a list');
    } else {
      m.overlaps.forEach((o, i) => {
        const where = `overlaps[${i}]`;
        if (!isObject(o) || !isText(o.file) || !isTextList(o.tasks) || o.tasks.length < 2
          || !isText(o.reason) || !isText(o.merge_owner)) {
          err(`${where}: must be {file, tasks (2 or more ids), reason, merge_owner}`);
          return;
        }
        if (normalizePath(o.file) === null) err(`${where}.file: ${JSON.stringify(o.file)} is absolute or leaves the project`);
        if (!o.tasks.includes(o.merge_owner)) err(`${where}.merge_owner: must be one of its tasks`);
        overlapFor.set(fileKey(o.file), o);
      });
    }
  }

  // Lanes: shape, unique lane ids, and no file claimed by two lanes unless an
  // overlaps entry records it.
  const laneIds = new Set();
  const laneOfTask = new Map();
  if ('lanes' in m) {
    if (!Array.isArray(m.lanes)) {
      err('lanes: must be a list');
    } else {
      const fileOwner = new Map();
      m.lanes.forEach((lane, i) => {
        const where = `lanes[${i}]`;
        if (!isObject(lane)) {
          err(`${where}: must be an object`);
          return;
        }
        if (!isText(lane.id)) err(`${where}.id: must be a non-empty string`);
        else if (!new RegExp(laneIdPattern()).test(lane.id)) {
          err(`${where}.id: lane id ${JSON.stringify(lane.id)} must match ${laneIdPattern()}`);
        } else if (lane.id === 'prelude' || lane.id === 'join') err(`lane ${lane.id}: id is reserved`);
        else if (laneIds.has(lane.id)) err(`lane ${lane.id}: id appears more than once`);
        else laneIds.add(lane.id);
        if (!isText(lane.name)) err(`${where}.name: must be a non-empty string`);
        if ('setup_note' in lane && !isText(lane.setup_note)) err(`${where}.setup_note: must be a non-empty string`);
        checkTaskList(`${where}.tasks`, lane.tasks);
        if (!isText(lane.id) || !Array.isArray(lane.tasks)) return;
        const files = new Map();
        for (const t of lane.tasks) {
          if (!isObject(t)) continue;
          if (isText(t.id)) laneOfTask.set(t.id, lane.id);
          if (isTextList(t.files)) t.files.forEach((f) => files.set(fileKey(f), { f, task: t.id }));
        }
        for (const [key, { f, task }] of files) {
          const owner = fileOwner.get(key);
          if (owner === undefined) {
            fileOwner.set(key, { lane: lane.id, task, f });
            continue;
          }
          if (owner.lane === lane.id) continue;
          const o = overlapFor.get(key);
          if (!o || !o.tasks.includes(task) || !o.tasks.includes(owner.task)) {
            err(`file ${f}: claimed by lanes ${owner.lane} and ${lane.id}` +
              (owner.f !== f ? ` (as ${owner.f} and ${f})` : '') +
              '; record a deliberate overlap in overlaps or keep it in one lane');
          }
        }
      });
    }
  }

  if ('join' in m) checkTaskList('join', m.join);

  // Every overlaps entry names known tasks that list its file.
  if (Array.isArray(m.overlaps)) {
    const files = new Map();
    for (const t of allTasks) if (isObject(t) && isText(t.id) && isTextList(t.files)) files.set(t.id, t.files.map(fileKey));
    m.overlaps.forEach((o, i) => {
      if (!isObject(o) || !isTextList(o.tasks)) return;
      for (const id of o.tasks) {
        if (!files.has(id)) err(`overlaps[${i}]: unknown task id ${id}`);
        else if (isText(o.file) && !files.get(id).includes(fileKey(o.file))) {
          err(`overlaps[${i}]: task ${id} does not list ${o.file} in its files`);
        }
      }
    });
  }

  // Dependencies: known ids, no cycles, and a code dependency that can be
  // met by the run order (the dependency runs earlier and its commits are in
  // the dependent's checkout): a prelude task, an earlier task of the same
  // lane, or anything before a join task.
  const position = new Map();
  const groupOf = new Map();
  let index = 0;
  const place = (list, group) => {
    if (!Array.isArray(list)) return;
    for (const t of list) {
      if (!isObject(t) || !isText(t.id)) continue;
      position.set(t.id, index);
      groupOf.set(t.id, group);
      index += 1;
    }
  };
  place(m.prelude, 'prelude');
  if (Array.isArray(m.lanes)) for (const lane of m.lanes) if (isObject(lane)) place(lane.tasks, `lane ${lane.id}`);
  place(m.join, 'join');
  const deps = new Map();
  for (const t of allTasks) {
    if (!isObject(t) || !isText(t.id) || !Array.isArray(t.depends_on)) continue;
    deps.set(t.id, []);
    for (const d of t.depends_on) {
      if (!isObject(d) || !isText(d.id)) continue;
      if (!taskIds.has(d.id)) {
        err(`task ${t.id}: depends_on names unknown task ${d.id}`);
        continue;
      }
      if (d.id === t.id) {
        err(`task ${t.id}: depends on itself`);
        continue;
      }
      deps.get(t.id).push(d.id);
      if (d.kind !== 'code') continue;
      const [mine, theirs] = [groupOf.get(t.id), groupOf.get(d.id)];
      const met = position.get(d.id) < position.get(t.id)
        && (theirs === 'prelude' || theirs === mine || mine === 'join');
      if (!met) {
        err(`task ${t.id}: code dependency on ${d.id} (${theirs}) cannot be met from ${mine}; ` +
          'move the task to join or the same lane, or make it a contract dependency');
      }
    }
  }
  const visiting = new Set();
  const visited = new Set();
  const cycle = (id) => {
    if (visited.has(id)) return false;
    if (visiting.has(id)) return true;
    visiting.add(id);
    const found = (deps.get(id) || []).some(cycle);
    visiting.delete(id);
    visited.add(id);
    return found;
  };
  for (const id of deps.keys()) {
    if (cycle(id)) {
      err(`depends_on: a dependency cycle runs through task ${id}`);
      break;
    }
  }

  // excluded: plan tasks the run leaves out (after-merge, operator, manual,
  // handled by a hook), each with the reason; scripts/coverage checks them
  // against the plan.
  if ('excluded' in m) {
    if (!Array.isArray(m.excluded)) {
      err('excluded: must be a list');
    } else {
      const seen = new Set();
      m.excluded.forEach((e, i) => {
        if (!isObject(e) || !isText(e.id) || !isText(e.reason)) {
          err(`excluded[${i}]: must be {id, reason}`);
          return;
        }
        if (taskIds.has(e.id)) err(`excluded[${i}]: task ${e.id} is also in the run`);
        if (seen.has(e.id)) err(`excluded[${i}]: task ${e.id} appears more than once`);
        seen.add(e.id);
      });
    }
  }
  if ('allow_deferral' in m && typeof m.allow_deferral !== 'boolean') err('allow_deferral: must be a boolean');

  if ('lane_commands' in m) {
    if (!isObject(m.lane_commands)) {
      err('lane_commands: must be an object');
    } else {
      for (const [laneId, cmds] of Object.entries(m.lane_commands)) {
        if (!laneIds.has(laneId)) err(`lane_commands.${laneId}: unknown lane id`);
        checkCommands(`lane_commands.${laneId}`, cmds, false);
      }
    }
  }

  if ('hooks' in m) {
    if (!isObject(m.hooks)) {
      err('hooks: must be an object');
    } else {
      for (const key of Object.keys(m.hooks)) {
        if (key !== 'post_integrate' && key !== 'e2e') err(`hooks.${key}: unknown hook`);
        else if (!isText(m.hooks[key])) err(`hooks.${key}: must be a non-empty string`);
      }
    }
  }

  if ('limits' in m) {
    if (!isObject(m.limits)) {
      err('limits: must be an object');
    } else {
      for (const key of ['review_rounds', 'max_parallel_lanes']) {
        if (!isPositiveInt(m.limits[key])) err(`limits.${key}: must be an integer >= 1`);
      }
      if ('max_agents' in m.limits && !isPositiveInt(m.limits.max_agents)) {
        err('limits.max_agents: must be an integer >= 1');
      }
      if ('max_rulings' in m.limits && !(Number.isInteger(m.limits.max_rulings) && m.limits.max_rulings >= 0)) {
        err('limits.max_rulings: must be an integer >= 0');
      }
    }
  }

  for (const key of ['done', 'reviewed', 'deferred']) {
    if (!(key in m)) continue;
    if (!isTextList(m[key])) {
      err(`${key}: must be a list of task ids`);
      continue;
    }
    for (const id of m[key]) {
      if (!taskIds.has(id)) err(`${key}: unknown task id ${id}`);
    }
  }
  // deferred: tasks the ledger lists as parked or unblocked (ledger status);
  // they are done for scheduling but keep the run from being accepted.
  if (isTextList(m.deferred) && isTextList(m.done)) {
    for (const id of m.deferred) if (!m.done.includes(id)) err(`deferred: task ${id} is not done`);
  }

  // notes: the user's answers to blocked questions, one text per task id;
  // each is passed to that task's agents.
  if ('notes' in m) {
    if (!isObject(m.notes)) {
      err('notes: must be an object');
    } else {
      for (const [id, text] of Object.entries(m.notes)) {
        if (!taskIds.has(id)) err(`notes: unknown task id ${id}`);
        if (!isText(text)) err(`notes.${id}: must be a non-empty string`);
      }
    }
  }

  // backfill: commits of done tasks, from ledger committed events. A done
  // but unreviewed task is reviewed before its lane continues; every head is
  // the next task's base.
  const backfill = 'backfill' in m ? m.backfill : {};
  if (!isObject(backfill)) {
    err('backfill: must be an object');
  } else {
    for (const [id, range] of Object.entries(backfill)) {
      if (!taskIds.has(id)) err(`backfill: unknown task id ${id}`);
      if (!isObject(range) || !isText(range.base) || !isText(range.head)) {
        err(`backfill.${id}: must be {base, head} with non-empty strings`);
      }
    }
    if (isTextList(m.done) && isTextList(m.reviewed)) {
      for (const id of m.done) {
        if (!(id in backfill)) err(`backfill: missing an entry for task ${id} (done)`);
      }
    }
  }

  // Lite profile (spec D2): one lane on the feature branch, a small plan, no
  // security task (it gets no separate security review lens), and no
  // post_integrate hook.
  if (m.profile === 'lite') {
    if (Array.isArray(m.lanes) && m.lanes.length !== 1) {
      err(`profile lite: requires exactly one lane (found ${m.lanes.length})`);
    }
    if (allTasks.length > 8) {
      err(`profile lite: allows at most 8 tasks across prelude, lanes and join (found ${allTasks.length})`);
    }
    for (const t of allTasks) {
      if (isObject(t) && t.security === true) {
        const name = isText(t.id) ? `task ${t.id}` : 'a task';
        err(`profile lite: allows no security task (${name} has security set)`);
      }
    }
    // Lite has no integration phase, so the hook would never run.
    if (isObject(m.hooks) && 'post_integrate' in m.hooks) {
      err('profile lite: not allowed with hooks.post_integrate (lite does not run it)');
    }
  }

  // setup_result: the output of scripts/setup. Every lane needs a worktree
  // entry so a run never starts a lane without its checkout (the run itself
  // checks each path against the one it uses).
  // A launch (dry_run false) needs it: scripts/setup is the only setup.
  if (m.dry_run === false && !('setup_result' in m)) {
    err('setup_result: missing; run scripts/setup after the yes to the table and add its output');
  }
  if ('setup_result' in m) {
    const r = m.setup_result;
    if (!isObject(r)) {
      err('setup_result: must be an object');
    } else {
      if (!isText(r.feature_head)) err('setup_result.feature_head: must be a non-empty string');
      if (!isTextList(r.discarded)) err('setup_result.discarded: must be a list of non-empty strings');
      if ('preserved' in r && !(Array.isArray(r.preserved) && r.preserved.every((p) => isObject(p)
        && isText(p.worktree) && isText(p.ref) && isText(p.commit)))) {
        err('setup_result.preserved: must be a list of {worktree, ref, commit}');
      }
      if (!isObject(r.worktrees)) {
        err('setup_result.worktrees: must be an object mapping lane ids to absolute paths');
      } else {
        for (const [laneId, path] of Object.entries(r.worktrees)) {
          if (!laneIds.has(laneId)) err(`setup_result.worktrees.${laneId}: unknown lane id`);
          if (!isAbsolutePath(path)) err(`setup_result.worktrees.${laneId}: must be an absolute path`);
        }
        for (const laneId of laneIds) {
          if (!(laneId in r.worktrees)) err(`setup_result.worktrees: missing a worktree for lane ${laneId}`);
        }
      }
    }
  }

  // start_points: feature heads from the ledger run_started events.
  if ('start_points' in m) {
    if (!isObject(m.start_points)) {
      err('start_points: must be an object');
    } else {
      for (const [key, sha] of Object.entries(m.start_points)) {
        if (key !== 'prelude' && key !== 'join') err(`start_points.${key}: unknown start point`);
        else if (!isText(sha)) err(`start_points.${key}: must be a non-empty string`);
      }
    }
  }

  return errors;
}

// The run's autonomy mode (spec C1): autonomous unless the manifest says
// supervised.
function effectiveAutonomy(m) {
  return m.autonomy === 'supervised' ? 'supervised' : 'autonomous';
}

// The run's budgets (spec C3) for a valid manifest: max_agents defaults to
// twice the dry-run estimate, max_rulings to 25.
function effectiveLimits(m) {
  const limits = m.limits;
  return {
    max_agents: 'max_agents' in limits ? limits.max_agents : 2 * planAgents(m).length,
    max_rulings: 'max_rulings' in limits ? limits.max_rulings : 25,
  };
}

// Model settings. The sonnet and light tiers apply to implementers of
// sonnet and light tasks only; reviewers always run standard. Integrate,
// e2e, and minor-only or docs-only final fixes start on Sonnet with settings
// of their own (phases.js).
function tierSettings(tier) {
  return tier === 'sonnet' || tier === 'light'
    ? { model: 'sonnet', effort: 'high' }
    : { model: 'opus', effort: 'high' };
}

// The agents a run would spawn, in run order:
// [{phase, lane|null, task|null, role, model, effort}].
// Per task: none if done and reviewed, a review if done only, else implement
// plus review. A batch (batchGroup) is one unit: one implement (unless it
// was committed in an earlier run) and one review, with task = the unit id
// (`<first>-<last>`, as in its agent labels). Implementers run on their
// task's tier. Reviews are listed at high effort: the diff size that allows
// medium (reviewSettings) is not known before the run. Fix rounds are not
// predictable, so each task review counts as one; a task can add up to 2x
// review_rounds more (fix plus re-review). There is no setup agent:
// scripts/setup runs before the launch. Profile lite has no pre-flight,
// integrate or post-integrate agent and one combined final reviewer.
// Integrate and e2e start on Sonnet. final_fix (Opus; Sonnet when every
// finding is minor or docs-only) and final_re_review are listed as the upper
// bound; they run only when the final reviews report findings. Verify: the
// verify agent (Sonnet) runs the project checks at the delivered revision
// whenever a test, lint or build command exists; e2e_recheck and
// post_integrate_recheck are listed as the upper bound: they run only when a
// later commit made the earlier result stale. Retries, adjudications,
// escalations, conflict resolution, and post-integrate fixes are not
// predictable either; the max_agents budget covers them. Expects a valid
// manifest.
function planAgents(m) {
  const agents = [];
  const standard = tierSettings('standard');
  const sonnetHigh = { model: 'sonnet', effort: 'high' };
  const lite = m.profile === 'lite';
  const add = (phase, lane, task, role, settings) =>
    agents.push({ phase, lane, task, role, ...settings });
  const addTasks = (phase, lane, tasks) => {
    for (let i = 0; i < tasks.length;) {
      const group = batchGroup(m, tasks, i);
      i += group.length;
      const state = taskState(m, group[0].id);
      if (state === 'skip') continue;
      const unit = group.length > 1 ? batchUnit(group) : group[0];
      if (state === 'run') add(phase, lane, unit.id, 'implement', tierSettings(unit.tier));
      add(phase, lane, unit.id, 'review', standard);
    }
  };

  if (!lite) add('Pre-flight', null, null, 'preflight', standard);
  addTasks('Prelude', null, m.prelude);
  for (const lane of m.lanes) addTasks(lane.name, lane.id, lane.tasks);
  if (!lite) {
    add('Integrate', null, null, 'integrate', sonnetHigh);
    if (m.hooks.post_integrate) add('Integrate', null, null, 'post_integrate', standard);
  }
  addTasks('Join', null, m.join);
  if (m.hooks.e2e) add('E2E', null, null, 'e2e', sonnetHigh);
  const lenses = lite
    ? ['final_review_combined']
    : ['final_review_sp', 'final_review_security', 'final_review_correctness'];
  for (const role of [...lenses, 'final_fix', 'final_re_review']) {
    add('Final review', null, null, role, standard);
  }
  if (['test', 'lint', 'build'].some((g) => (m.commands[g] || []).length > 0)) add('Verify', null, null, 'verify', sonnetHigh);
  if (m.hooks.e2e) add('Verify', null, null, 'e2e_recheck', sonnetHigh);
  if (!lite && m.hooks.post_integrate) add('Verify', null, null, 'post_integrate_recheck', standard);
  return agents;
}

// Lanes that would run at once: lanes with at least one planned agent,
// capped by limits.max_parallel_lanes.
function lanesEffective(m, agents) {
  const active = new Set(agents.filter((a) => a.lane !== null).map((a) => a.lane));
  return Math.min(active.size, m.limits.max_parallel_lanes);
}

// Progress phase of a ledger lane: prelude and join tasks have their own
// phases; lane tasks use the lane's name.
function lanePhase(m, laneId) {
  if (laneId === 'prelude') return 'Prelude';
  if (laneId === 'join') return 'Join';
  const lane = m.lanes.find((l) => l.id === laneId);
  return lane ? lane.name : laneId;
}

// Where a lane's tasks run: its own worktree and run branch. sync is the
// feature branch the lane fast-forwards to before implementing (it holds the
// prelude commits made after setup created the lane branch).
function laneWhere(m, lane) {
  return {
    dir: `${m.repo.worktree_root}/lane-${lane.id}`,
    branch: `pl-${m.run_id}-${lane.id}`,
    lane: lane.id,
    sync: m.repo.branch,
  };
}

// The checkout of the feature branch: the main checkout in git mode; in
// shadow mode a worktree of the shadow repo (the project folder itself is
// never written during a run).
function featureDir(m) {
  return m.repo.mode === 'shadow' ? `${m.repo.worktree_root}/feature` : m.repo.root;
}

// Where prelude and join tasks run, with their ledger lane.
function featureWhere(m, ledgerLane) {
  return { dir: featureDir(m), branch: m.repo.branch, lane: ledgerLane };
}

// Scratch files for a task, kept in the ledger dir (outside every repo).
function taskFiles(m, task) {
  const dir = m.repo.ledger_dir;
  return {
    brief: `${dir}/briefs/${task.id}.md`,
    report: `${dir}/reports/${task.id}.md`,
    reviews: `${dir}/reviews`,
  };
}

// What a run does with a task: 'skip' (done and reviewed), 'review'
// (done, not reviewed: backfill review first), or 'run'.
function taskState(m, id) {
  if (!m.done.includes(id)) return 'run';
  return m.reviewed.includes(id) ? 'skip' : 'review';
}

// Tasks of a group (prelude, a lane, join) that still need an agent.
function hasWork(m, tasks) {
  return tasks.some((t) => taskState(m, t.id) !== 'skip');
}

// The tasks a unit of work covers. A batch unit (spec D3) is consecutive
// light tasks with the same batch key run by one implementer and one review:
// {id: '<first>-<last>', title, files, tier, security, batch, tasks}. A
// plain task covers itself.
function unitTasks(task) {
  return Array.isArray(task.tasks) ? task.tasks : [task];
}

function isBatch(task) {
  return Array.isArray(task.tasks);
}

// 'batch' for a batch unit, 'task' otherwise.
function unitNoun(task) {
  return isBatch(task) ? 'batch' : 'task';
}

// How prompts name a unit: 'Task <id>: <title>', or for a batch
// 'Batch <first>-<last>: Task <id>: <title>; ...'.
function unitName(task) {
  if (!isBatch(task)) return `Task ${task.id}: ${task.title}`;
  return `Batch ${task.id}: ${task.tasks.map((t) => `Task ${t.id}: ${t.title}`).join('; ')}`;
}

// The ledger command for one event, for every task of a unit, as indented
// prompt lines. A batch's events are per task (its commits are attributed to
// the batch range).
function ledgerLines(m, task, where, entry) {
  return unitTasks(task).map((t) => `  ${ledgerCommand(m, where.lane, { task: t.id, ...entry }, where.dir)}`);
}

// The [BRIEF_FILE] a superpowers prompt is given: the task's brief, or for a
// batch the briefs taskContext lists.
function briefRef(m, task) {
  return isBatch(task) ? 'the task briefs listed below (one per task, in order)' : taskFiles(m, task).brief;
}

// What a batch agent is told about the batch, or nothing for a plain task.
function batchLines(task) {
  if (!isBatch(task)) return [];
  const ids = task.tasks.map((t) => t.id).join(', ');
  return [
    `This is a batch of ${task.tasks.length} tasks (${ids}) run as one unit: one implementer, one review over the`,
    'combined range, one report file. Its briefs are listed below, one per task. The tasks are implemented in',
    'that order, one commit per task with the message its brief gives; every ledger event is recorded for each',
    'task.',
  ];
}

// The exact ledger append command for one event. dir is the checkout of
// the agent that runs it (where.dir for task agents, featureDir(m) for phase
// agents and lane _run events): like every provided command, it starts there.
function ledgerCommand(m, laneId, entry, dir) {
  if (!present(dir)) throw new Error('ledgerCommand: dir (the agent checkout) is required');
  const ledger = `${m.skill_dir}/scripts/ledger`;
  return `cd ${shellQuote(dir)} && python3 ${shellQuote(ledger)} append ${shellQuote(m.repo.ledger_dir)} ` +
    `${shellQuote(laneId)} ${shellQuote(JSON.stringify(entry))}`;
}

// The commands of one group for a ledger lane (null: project commands only);
// lane_commands override per group.
function commandGroup(m, laneId, name) {
  const own = (laneId !== null && m.lane_commands && m.lane_commands[laneId]) || {};
  return own[name] || m.commands[name] || [];
}

// One command group as a shell line: joined with &&, so a failing command
// fails the line instead of hiding behind the next one's success.
function commandList(m, laneId, name) {
  const list = commandGroup(m, laneId, name);
  return list.length > 0 ? list.join(' && ') : '(none)';
}

// The scripts/run-checks call that runs every test, lint and build command
// of a ledger lane in dir, each separately, and exits non-zero when any one
// fails (the setup group is not a check). out (optional) is the evidence file
// it writes under the ledger dir. null when there is no check command.
function checksCommand(m, laneId, dir, out = null) {
  const parts = [];
  for (const name of ['test', 'lint', 'build']) {
    for (const cmd of commandGroup(m, laneId, name)) parts.push('--cmd', shellQuote(name), shellQuote(cmd));
  }
  if (parts.length === 0) return null;
  const evidence = out === null ? [] : ['--out', shellQuote(out), '--root', shellQuote(m.repo.ledger_dir)];
  return [`cd ${shellQuote(dir)} && python3 ${shellQuote(`${m.skill_dir}/scripts/run-checks`)}`, shellQuote(dir),
    ...evidence, ...parts].join(' ');
}

// Project commands for a ledger lane; with dir, also the run-checks call that
// runs every check there at once.
function commandsText(m, laneId, dir = null) {
  const lines = ['setup', 'test', 'lint', 'build'].map((name) => `- ${name}: ${commandList(m, laneId, name)}`);
  const all = dir === null ? null : checksCommand(m, laneId, dir);
  if (all !== null) {
    lines.push(`- every check at once (each command's exit status is kept; it exits non-zero when any fails):\n  ${all}`);
  }
  return lines.join('\n');
}

function findingsText(findings) {
  if (!Array.isArray(findings) || findings.length === 0) return '(none listed)';
  return findings.map((f, i) => `${present(f.id) ? `[${f.id}]` : `${i + 1}.`} [${f.severity}] ${f.file}:${f.line}`
    + ` - ${f.issue} (suggested fix: ${f.fix})`).join('\n');
}

// The note for a finding with file "start-task" (reviewStartFailure): the
// reviewer's start command failed, which no code change in the worktree can
// fix. Empty when no finding has that file.
function startFindingNote(findings) {
  if (!Array.isArray(findings) || !findings.some((f) => f && f.file === 'start-task')) return [];
  return ['A finding with file "start-task" is the reviewer\'s start command failing (a setup problem, not the',
    'code): change no code for it, and when it is the only finding, report blocked quoting it.'];
}

// Shared context every task agent gets. guidance (optional) is
// {notes, amendments}: notes are decided on the user's behalf in this run (an
// adjudicator answer, or a note an unblocked task carries to the next one);
// amendments are adjudicator rulings that amend the task's brief for this run.
function taskContext(m, task, where, guidance = null) {
  const files = taskFiles(m, task);
  const tasks = unitTasks(task);
  const userNote = (t) => m.notes && m.notes[t.id];
  // A batch records its rulings under its first task.
  const ruling = ledgerCommand(m, where.lane,
    { task: tasks[0].id, event: 'ruling', text: 'Ruling: <decision> - <why> - <cost if wrong>' }, where.dir);
  const runNotes = (guidance && guidance.notes) || [];
  const amendments = (guidance && guidance.amendments) || [];
  const briefs = isBatch(task) ? [
    'Task briefs, one per task. The start command in this prompt regenerates each from the current plan and prints it',
    '(it overwrites any older copy, so plan fixes made since an earlier attempt reach you):',
    ...tasks.map((t) => `- Task ${t.id}: ${taskFiles(m, t).brief}`),
    ...tasks.filter(userNote).map((t) =>
      `The user's answer for task ${t.id} (follow it where it settles a question): ${userNote(t)}`),
  ] : [
    `Task brief: ${files.brief}. The start command in this prompt regenerates it from the current plan and prints it`,
    '(it overwrites any older copy, so plan fixes made since an earlier attempt reach you).',
    ...(userNote(task)
      ? [`The user's answer for this task (follow it where it settles a question): ${userNote(task)}`] : []),
  ];
  return [
    unitName(task),
    `Plan: ${m.plan}`,
    `Spec: ${m.spec === null ? '(none)' : m.spec}`,
    `Worktree: ${where.dir} (branch ${where.branch}). Work only there; do not switch branches.`,
    checkoutRules(where.dir, where.branch),
    ...briefs,
    ...runNotes.map((n) =>
      `A note decided on the user's behalf for this ${unitNoun(task)} (follow it where it settles a question): ${n}`),
    ...amendments.map((a) => (isBatch(task)
      ? `Amendment to the batch's task briefs for this run (it overrides the briefs where they differ): ${a}`
      : `Amendment to the task brief for this run (it overrides the brief where they differ): ${a}`)),
    `Implementer report file: ${files.report}`,
    '',
    'Project commands (run from the worktree):',
    commandsText(m, where.lane, where.dir),
    '',
    `Commit rules (follow exactly): ${m.commit_rules}`,
    'Never commit anything under .superpowers/.',
    'Never push, open pull requests, merge into the base branch, or copy work back to the project.',
    agentRules(),
    '',
    'Contracts: report blocked for any change to a contract another lane consumes; ' +
      'record smaller decisions as `Ruling: decision - why - cost if wrong` with:',
    `  ${ruling}`,
    'Ledger entries are shell single-quoted JSON: fill the <...> placeholders and keep quote characters out of the text.',
  ].join('\n');
}

