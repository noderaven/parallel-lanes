// A schema-valid adjudicator result reduced to its known fields, or null
// when it is not valid (a stop without a valid stop condition included).
function adjudicatorResult(r) {
  if (r === null || typeof r !== 'object' || Array.isArray(r)) return null;
  if (!adjudicatorOutcomes().includes(r.outcome) || typeof r.text !== 'string') return null;
  const hasCondition = r.stop_condition !== undefined;
  if (hasCondition && !adjudicatorStopConditions().includes(r.stop_condition)) return null;
  if (r.outcome === 'park' || r.outcome === 'unblock') {
    return { outcome: r.outcome, text: r.text, ...(present(r.head) ? { head: r.head } : {}) };
  }
  if (r.outcome !== 'stop') return { outcome: r.outcome, text: r.text };
  if (!hasCondition) return null;
  return { outcome: 'stop', text: r.text, stop_condition: r.stop_condition };
}

// One adjudication. Returns the outcome object; never null.
async function adjudicate(m, ctx, io = { agent, log }) {
  const label = ctx.task ? `${ctx.task.id} adjudicate` : 'run adjudicate';
  const phaseName = ctx.kind === 'preflight' || !ctx.where ? 'Pre-flight' : lanePhase(m, ctx.where.lane);
  const r = await io.agent(adjudicatorPrompt(m, ctx),
    { label, phase: phaseName, schema: adjudicatorSchema(), model: 'opus', effort: 'high' });
  if (r === null || r === undefined) {
    return { outcome: 'stop', text: `no result from ${label}`, stop_condition: 'plan_broken', unavailable: true };
  }
  const valid = adjudicatorResult(r);
  if (valid === null) {
    return {
      outcome: 'stop', text: 'adjudicator returned an invalid result', stop_condition: 'plan_broken', invalid: true,
    };
  }
  return valid;
}

// Run budgets: caps on agents, adjudicator rulings, and final fix waves.
//
// makeIo wraps io.agent so every spawn of the run goes through one place:
// it retries a dead agent (null result) once, counts agents and rulings in
// state ({agents, rulings, refused, untyped?, typedNulls?}), and refuses
// calls past the limits of effectiveLimits(m). A refused call spawns nothing and returns the
// sentinel {__budget: true}; callers read it as a blocked or invalid result,
// and runAll stops the run with reason budget. Once one call is refused every
// later call is refused too, so no new agent starts while the ones in flight
// finish. The other io members pass through unchanged.
//
// Agent type: when agentTypeFor(m, label) names one, the spawn carries
// agentType. A typed spawn that throws or returns null is retried once as
// "<label> retry" without agentType through the normal checks. Counting is
// the same as for any spawn: the failed typed spawn stays counted (it may
// have run before it failed), and the retry counts again. The latch
// state.untyped (created on first use; missing means false) then sends every
// later spawn of the run, in any lane, out untyped, so a missing or broken
// definition cannot double every agent: it is set by the first typed spawn
// that throws, and by the second typed spawn that returns null while its
// untyped retry returns a result (state.typedNulls counts those; one dead
// agent alone is not a sign of a broken type). runAll reports the latch as
// agent_type_fallback. Untyped spawns retry on null only; their throw
// propagates.
function makeIo(m, baseIo, state) {
  const limits = effectiveLimits(m);
  const refuse = (label) => {
    state.refused.push(label);
    baseIo.log(`parallel-lanes: budget exhausted: ${label} was not run`);
    return { __budget: true };
  };
  const isRuling = (label) => / adjudicate( retry)?$/.test(label);
  const spawn = (prompt, opts) => {
    const label = opts.label;
    if (state.refused.length > 0 || state.agents >= limits.max_agents) return refuse(label);
    const ruling = isRuling(label);
    if (ruling && state.rulings >= limits.max_rulings) return refuse(label);
    // Only calls that run count: state.rulings is the adjudications spent.
    if (ruling) state.rulings += 1;
    state.agents += 1;
    return baseIo.agent(prompt, opts);
  };
  return {
    ...baseIo,
    agent: async (prompt, opts) => {
      const retry = () => spawn(prompt, { ...opts, label: `${opts.label} retry` });
      const agentType = state.untyped ? null : agentTypeFor(m, opts.label);
      if (agentType === null) {
        const r = await spawn(prompt, opts);
        if (r !== null && r !== undefined) return r;
        return retry();
      }
      const fallBack = (why) => {
        if (!state.untyped) {
          baseIo.log(`parallel-lanes: ${opts.label} failed as agent type ${agentType} (${why});`
            + ' it and every later agent run on the default type');
        }
        state.untyped = true;
      };
      let r;
      try {
        r = await spawn(prompt, { ...opts, agentType });
      } catch (e) {
        fallBack(e && e.message ? e.message : String(e));
        return retry();
      }
      if (r !== null && r !== undefined) return r;
      const again = await retry();
      if (again !== null && again !== undefined && !(again && again.__budget)) {
        state.typedNulls = (state.typedNulls || 0) + 1;
        if (state.typedNulls >= 2) fallBack('a second typed agent returned no result and its untyped retry did');
      }
      return again;
    },
  };
}

// The custom agent type for a spawn: m.agent_type, except for the hook agents
// (e2e and post-integrate, and their rechecks) and the post-integrate fix,
// which must keep the post-integrate hook passing: hook instructions may need
// any tool.
function agentTypeFor(m, label) {
  if (typeof m.agent_type !== 'string' || m.agent_type.length === 0) return null;
  if (/^(e2e|e2e recheck|post-integrate|post-integrate recheck|post-integrate fix)( retry)?$/.test(label)) return null;
  return m.agent_type;
}

// ---- Execution engine: per-task loop and lanes ----
//
// Every function below is pure over its parameters (no top-level const/let),
// so tests can load them with loadHelpers. The run functions take a trailing
// io object {agent, log} that defaults to the Workflow globals.

// Model and effort for a task review or re-review (spec D4): always Opus, at
// medium effort when the task is not security-flagged and the diff under
// review has fewer than 60 changed lines, else high. changedLines is the
// changed_lines the agent whose work is under review returned; a missing or
// malformed count means high.
function reviewSettings(task, changedLines) {
  const small = Number.isInteger(changedLines) && changedLines >= 0 && changedLines < 60;
  return { model: 'opus', effort: !task.security && small ? 'medium' : 'high' };
}

// A review or re-review result checked across its fields, not just its
// shape: an approve that carries a critical or important finding is acted on
// as changes (the gate never takes a self-contradicting approval; contradicted
// says so), and changes with no findings gives the fixer nothing to fix, so it
// is unusable (invalid says why). A budget sentinel or a missing result passes
// through as it is.
function checkedReview(v) {
  if (!v || v.__budget) return v;
  if (v.verdict !== 'approve' && v.verdict !== 'changes') return { ...v, invalid: `unknown verdict ${v.verdict}` };
  const findings = Array.isArray(v.findings) ? v.findings : [];
  if (v.verdict === 'approve' && findings.some(isBlocking)) {
    return { ...v, verdict: 'changes', findings, contradicted: true };
  }
  if (v.verdict === 'changes' && findings.length === 0) return { ...v, findings, invalid: 'changes with no findings' };
  return { ...v, findings };
}

// Run one task through implement -> review -> fix/re-review rounds. task may
// be a batch unit (batchUnit): its agents use the unit id in their labels
// (`<first>-<last> implement`), its prompts cover every task of the batch, and
// it is adjudicated as its first task.
// Tiers (spec D5): a sonnet or light task implements and fixes on its tier's
// settings and escalates to standard when an implement or fix does not
// finish (not on a question), a sonnet task also after the first changes
// verdict, a light task after the second; escalation reruns implement at
// standard from the current head with the open findings, then reviews the
// whole task range. Reviews use reviewSettings with the changed_lines of the
// implement or fix result under review.
// Returns {task, status:'done'|'deferred'|'blocked', base, head, rounds,
// tier_used, notes, rulings, next_note?}; for a blocked task notes is the reason (exactly
// 'review_rounds' at the cap in supervised mode, 'adjudication_cap', or
// 'adjudicator_stop: <condition>').
// base is owned by the script (the previous task's head, or the feature tip):
// every review range starts there, so commits of an earlier failed attempt
// are reviewed too. resume ({base, head}, optional) is a task committed in an
// earlier run but not reviewed: implement is skipped and the loop starts with
// the review of base..resume.head. note (optional) is carried from the
// lane's previous task (an adjudicator unblock).
//
// Autonomous mode (spec C1): where supervised mode stops the task (an
// implement or fix that does not finish, an implementer question, a review
// with no result, the review round cap), the adjudicator decides instead,
// at most twice per task. answer and clarify_plan rerun implement with the
// ruling as a note or a brief amendment, then review the whole task range;
// park and unblock end the task as deferred, never done: the range is the
// one the adjudicator recorded from git (finish-task --settled, its head
// returned), which keeps commits a blocked agent made attributed to this task;
// a deferred task keeps the run from being accepted. stop blocks the task.
// rulings lists each ruling text. A security-flagged task is never parked or
// unblocked (deferring a security requirement is the user's call, whatever
// the findings say): it stops with 'adjudicator_stop: security'. With
// allow_deferral false no task is: 'adjudicator_stop: deferral_not_allowed'.
async function runTask(m, task, where, base, io = { agent, log }, resume = null, note = null) {
  const phaseName = lanePhase(m, where.lane);
  const autonomous = effectiveAutonomy(m) === 'autonomous';
  let tierUsed = task.tier;
  let head = null;
  // Where an agent that did not finish left the branch (its reported head):
  // separate from head, the accepted implementation.
  let observed = null;
  let rounds = 0;
  let changesSeen = 0;
  let latest = null;
  let verdict = null;
  let adjudications = 0;
  // The latest review approved with a blocking finding (checkedReview): the
  // next implement or fix that runs reopens any approval it recorded.
  let reopen = false;
  // An agent that received the reopen command ran (not a budget refusal).
  const ran = (r) => r !== null && r !== undefined && !r.__budget;
  const extra = [];
  const rulings = [];
  const guidance = { notes: note ? [note] : [], amendments: [] };

  const result = (status, notes, more = {}) =>
    ({ task: task.id, status, base, head, rounds, tier_used: tierUsed, notes, rulings, ...more });
  const call = (role, prompt, settings, schema) =>
    io.agent(prompt, { label: `${task.id} ${role}`, phase: phaseName, schema, ...settings });
  const escalate = (reason) => {
    tierUsed = 'standard';
    extra.push(`escalated to standard: ${reason}`);
    io.log(`${task.id}: escalating to standard (${reason})`);
  };
  // Why an implement or fix result did not move the branch past from, as
  // {kind: 'budget'|'blocked'|'question', reason}; null when it did. A budget
  // refusal (the sentinel the run budget returns once the agent cap is hit)
  // ends the task without adjudication: no agent can be spawned to settle it.
  // In supervised mode a question is just a blocked result.
  const failure = (r, label, from) => {
    const blockedBy = (reason) => ({ kind: 'blocked', reason });
    if (r && r.__budget) return { kind: 'budget', reason: `${label} was not run` };
    if (r === null || r === undefined) return blockedBy(`no result from ${label}`);
    if (r.status === 'question') {
      const q = present(r.question) ? r.question : (present(r.notes) ? r.notes : '(no question text)');
      return { kind: autonomous ? 'question' : 'blocked', reason: `${label} asked a question: ${q}` };
    }
    if (r.status !== 'done') return blockedBy(`${label} blocked: ${r.notes}`);
    if (!present(r.head)) return blockedBy(`${label} reported no head`);
    if (r.head === from) return blockedBy(`${label} reported done with no new commits`);
    return null;
  };
  // A sonnet or light task escalates on a failure, except on a question it
  // can have answered by the adjudicator instead.
  const escalates = (fail) => tierUsed !== 'standard' && fail.kind !== 'question' && fail.kind !== 'budget';
  // Implement, escalating a sonnet or light task once if it does not finish. from
  // (optional) is the head the result must move past; it defaults to the
  // current head (or base before the first commit).
  const implement = async (retry, from = null) => {
    for (;;) {
      const past = from !== null ? from : (head === null ? base : head);
      const r = await call('implement', implementPrompt(m, task, where, base, retry, guidance, reopen),
        tierSettings(tierUsed), implementSchema());
      if (ran(r)) reopen = false;
      const fail = failure(r, `${task.id} implement`, past);
      if (fail === null) {
        head = r.head;
        observed = null;
        latest = r;
        return null;
      }
      if (r && !r.__budget && present(r.head) && r.head !== past) observed = r.head;
      if (!escalates(fail)) return fail;
      escalate(fail.reason);
      retry = { reason: fail.reason, findings: null };
    }
  };
  let reviewLabel = 'review';
  const review = async () => {
    reviewLabel = 'review';
    return checkedReview(await call('review', reviewPrompt(m, task, where, base, head, rounds, guidance),
      reviewSettings(task, latest.changed_lines), reviewSchema()));
  };

  // Escalate a sonnet or light task: rerun implement at standard from the
  // current head with the open findings, then review the whole task range
  // again.
  const rerunAtStandard = async (reason, findings) => {
    escalate(reason);
    const fail = await implement({ reason, findings });
    if (fail !== null) return fail;
    verdict = await review();
    return null;
  };

  // The notes of a completed task: escalations, the latest implementer
  // notes, then more.
  const doneNotes = (more) => {
    const notes = [...extra];
    if (latest && latest.notes) notes.push(latest.notes);
    return [...notes, ...more].join('\n');
  };

  // Parking or unblocking defers the task's requirements. A security task's
  // are never deferred by the adjudicator, and allow_deferral false means no
  // task's are: the reason, or null when deferral is open.
  const deferralRefused = () => {
    if (unitTasks(task).some((t) => t.security === true)) return 'security';
    if (m.allow_deferral === false) return 'deferral_not_allowed';
    return null;
  };

  // What the adjudicator is told about the task: the diff range (including
  // commits an agent that did not finish left), the report file, the reason
  // or question, and the finish-task --settled command a park or unblock
  // runs (it records the range git has and prints its head, which the
  // adjudicator returns). For a batch, the tasks it covers come first and the
  // command names every task. With deferral refused there is no command.
  const details = (need) => {
    const at = observed !== null ? observed : head;
    const lines = [
      ...(isBatch(task) ? [`Batch ${task.id}: tasks ${unitTasks(task).map((t) => t.id).join(', ')} run as one ` +
        'unit (one implementer, one review over the combined range); your outcome applies to all of them.'] : []),
      `Diff range: ${at === null ? `${base} (no commits reported yet; check the checkout)` : `${base}..${at}`}`,
      `Implementer report file: ${taskFiles(m, task).report}`,
      `${need.kind === 'question' ? 'Question' : 'Reason'}: ${need.reason}`,
    ];
    const refused = deferralRefused();
    if (refused === null) {
      for (const outcome of ['park', 'unblock']) {
        lines.push(`For outcome ${outcome}, run this command; it records the task as deferred (never accepted) with`,
          'the range git has, and prints JSON whose head you return as head:',
          `  ${finishCommand(m, task, where, base, outcome)}`);
      }
    } else {
      lines.push(refused === 'security'
        ? 'This task is security-flagged: park and unblock are not available; a deferral is the user\'s decision.'
        : 'Deferral is not allowed in this run (allow_deferral false): park and unblock are not available.');
    }
    return lines.join('\n');
  };

  // A point where the task cannot go on by itself: need = {kind, reason,
  // findings}. Returns the task result when the task ends here, or null
  // when the adjudicator's answer or amendment is in guidance and implement
  // should rerun. Only a valid ruling is listed in rulings (not an agent
  // error, an invalid result, or a budget refusal).
  const settle = async (need) => {
    if (!autonomous) return result('blocked', need.kind === 'round_cap' ? 'review_rounds' : need.reason);
    if (adjudications >= 2) return result('blocked', 'adjudication_cap');
    adjudications += 1;
    const findings = need.findings || [];
    // A batch is adjudicated as its first task.
    let out = await adjudicate(m,
      { kind: need.kind, task: unitTasks(task)[0], where, details: details(need), findings }, io);
    const deferring = out.outcome === 'park' || out.outcome === 'unblock';
    const refused = deferring ? deferralRefused() : null;
    // An open park or unblock must say where the settled range ends: the head
    // finish-task --settled printed. Without it the range is unknown, so the
    // result is invalid (a plan_broken stop that is not a ruling).
    if (deferring && refused === null && !present(out.head)) {
      out = { outcome: 'stop', stop_condition: 'plan_broken', invalid: true,
        text: 'adjudicator chose park or unblock without the settled head (if it ran the settled command, '
          + 'the ledger holds the task as deferred: check ledger status before resuming)' };
    }
    // A park or unblock the policy refuses never took effect, so it is listed
    // as refused, not as a ruling made on the user's behalf.
    if (!out.unavailable && !out.invalid) {
      rulings.push(refused === 'security' ? `refused (security-gated): ${out.text}`
        : refused !== null ? `refused (${refused}): ${out.text}` : out.text);
    }
    io.log(`${task.id}: adjudicated ${need.kind} -> ${out.outcome}`);
    if (out.outcome === 'stop') {
      return result('blocked', out.unavailable ? out.text : `adjudicator_stop: ${out.stop_condition}`);
    }
    if (refused !== null) {
      io.log(`${task.id}: ${out.outcome} refused (${refused})`);
      return result('blocked', `adjudicator_stop: ${refused}`);
    }
    if (deferring) {
      // The range finish-task --settled recorded: its head, read from git.
      head = out.head;
      const verb = out.outcome === 'park' ? 'parked' : 'unblocked';
      const notes = doneNotes([
        `deferred, not accepted: ${verb} (${need.kind}): ${need.reason}`,
        `adjudicator: ${out.text}`,
        ...findings.map((f) => `deferred finding [${f.severity}]: ${f.file}:${f.line} - ${f.issue}`),
      ]);
      return result('deferred', notes, out.outcome === 'unblock' ? { next_note: out.text } : {});
    }
    if (out.outcome === 'answer') guidance.notes.push(out.text);
    else guidance.amendments.push(out.text);
    if (need.kind === 'round_cap') rounds = 0;
    return null;
  };

  let need = null;
  if (resume) {
    head = resume.head;
    latest = { status: 'done', head, tests: '(committed in an earlier run)', notes: '' };
    verdict = await review();
  } else {
    const fail = await implement(null);
    if (fail !== null) need = { ...fail, findings: null };
    else verdict = await review();
  }
  // The findings the latest review or re-review was verifying.
  let open = null;
  for (;;) {
    if (need !== null) {
      if (need.kind === 'budget') return result('blocked', need.reason);
      const ended = await settle(need);
      if (ended !== null) return ended;
      // A rerun after an adjudication only has to leave a non-empty task
      // range: the work under review may already be right.
      const fail = await implement({ reason: need.reason, findings: need.findings }, base);
      if (fail !== null) {
        need = { ...fail, findings: need.findings };
        continue;
      }
      need = null;
      verdict = await review();
    }
    if (verdict && verdict.__budget) {
      need = { kind: 'budget', reason: `${task.id} ${reviewLabel} was not run` };
      continue;
    }
    if (!verdict || verdict.invalid) {
      const why = verdict ? `invalid result from ${task.id} ${reviewLabel}: ${verdict.invalid}`
        : `no result from ${task.id} ${reviewLabel}`;
      need = { kind: 'blocked', reason: why, findings: open };
      continue;
    }
    if (verdict.contradicted) {
      io.log(`${task.id}: ${reviewLabel} approved with a critical or important finding; acting on it as changes`);
      reopen = true;
    }
    if (verdict.verdict === 'approve') break;
    changesSeen += 1;
    const findings = verdict.findings;
    open = findings;
    const escalateAfter = { sonnet: 1, light: 2 }[tierUsed];
    if (changesSeen === escalateAfter) {
      const reason = escalateAfter === 1 ? 'review requested changes' : 'review requested changes twice';
      const fail = await rerunAtStandard(reason, findings);
      if (fail !== null) need = { ...fail, findings };
      continue;
    }
    if (rounds >= m.limits.review_rounds) {
      const reason = `the review round cap (${rounds} fix rounds) tripped with findings open`;
      need = { kind: 'round_cap', reason, findings };
      continue;
    }
    rounds += 1;
    const fixLabel = `fix ${rounds}`;
    const fix = await call(fixLabel, fixPrompt(m, task, where, findings, latest, head, guidance, reopen),
      tierSettings(tierUsed), implementSchema());
    if (ran(fix)) reopen = false;
    let fail = failure(fix, `${task.id} ${fixLabel}`, head);
    if (fail !== null && fix && !fix.__budget && present(fix.head) && fix.head !== head) observed = fix.head;
    if (fail !== null && escalates(fail)) fail = await rerunAtStandard(fail.reason, findings);
    else if (fail === null) {
      const prevHead = head;
      head = fix.head;
      latest = fix;
      reviewLabel = `re-review ${rounds}`;
      verdict = checkedReview(await call(reviewLabel,
        reReviewPrompt(m, task, where, prevHead, head, findings, rounds, guidance),
        reviewSettings(task, fix.changed_lines), reviewSchema()));
    }
    if (fail !== null) need = { ...fail, findings };
  }

  const notes = [];
  for (const f of verdict.findings || []) notes.push(`${f.severity} finding: ${f.file}:${f.line} - ${f.issue}`);
  for (const item of verdict.cannot_verify || []) notes.push(`cannot verify: ${item}`);
  return result('done', doneNotes(notes));
}

// One batch unit (spec D3) for consecutive light tasks with the same batch
// key: id '<first>-<last>', run on the light tier.
function batchUnit(tasks) {
  const first = tasks[0];
  return {
    id: `${first.id}-${tasks[tasks.length - 1].id}`,
    title: `batch of ${tasks.map((t) => t.id).join(', ')}`,
    files: tasks.flatMap((t) => t.files),
    tier: 'light',
    security: false,
    batch: first.batch,
    tasks,
  };
}

// The tasks that run as one unit starting at tasks[i]: tasks[i] and the
// tasks right after it with the same batch key and state, when that state
// is run, or review with an identical backfill range (a batch committed in
// an earlier run). Otherwise (no key, skip state, review without a range,
// or no matching neighbour) tasks[i] alone.
function batchGroup(m, tasks, i) {
  const first = tasks[i];
  const state = taskState(m, first.id);
  const backfill = m.backfill || {};
  const range = backfill[first.id];
  if (!present(first.batch) || state === 'skip' || (state === 'review' && !range)) return [first];
  const joins = (t) => {
    if (t.batch !== first.batch || taskState(m, t.id) !== state) return false;
    if (state === 'run') return true;
    const r = backfill[t.id];
    return Boolean(r) && r.base === range.base && r.head === range.head;
  };
  let j = i + 1;
  while (j < tasks.length && joins(tasks[j])) j += 1;
  return tasks.slice(i, j);
}

// Run tasks in order at where, starting from base; skip done-and-reviewed
// tasks, review done-only tasks first; stop at the first task that is not
// done. Each task's base is the previous task's head (a skipped task's from
// its backfill entry); a note an unblocked task carries goes to the next task
// that runs. Returns {results, stopped:reason|null, head} where head
// is the last known head (base when no task moved it).
// Batches (batchGroup) run as one unit through runTask; a finished batch
// gives each of its tasks a result with the batch range and batch: unit id,
// and a batch that is not done stops the list at its first task.
// baseIsPhaseTip: base is a head a phase agent reported (setup's feature head,
// the integrate or post-integrate head). On a resume that tip can already sit
// at or past this list's commits, so a done but unreviewed task that no
// earlier task in the list precedes is reviewed on its backfill range instead.
async function runTaskList(m, tasks, where, base, io, name, baseIsPhaseTip = false) {
  const results = [];
  let prev = base;
  let prevIsPhaseTip = baseIsPhaseTip;
  // Notes unblocked tasks carry, by the task id they go to: the later tasks
  // of the list that declare a dependency on the unblocked task, else the
  // next task (a plan without depends_on).
  const carried = new Map();
  const carry = (unit, i, text) => {
    const ids = unitTasks(unit).map((t) => t.id);
    const later = tasks.slice(i);
    const dependents = later.filter((t) => (t.depends_on || []).some((d) => ids.includes(d.id)));
    for (const t of dependents.length > 0 ? dependents : later.slice(0, 1)) {
      carried.set(t.id, [...(carried.get(t.id) || []), `from ${unit.id}, unblocked by the adjudicator: ${text}`]);
    }
  };
  for (let i = 0; i < tasks.length;) {
    const group = batchGroup(m, tasks, i);
    i += group.length;
    const task = group[0];
    const state = taskState(m, task.id);
    const range = (m.backfill || {})[task.id];
    if (state === 'skip') {
      results.push({
        task: task.id, status: 'skipped', base: range ? range.base : null, head: range ? range.head : null,
        rounds: null, tier_used: null, notes: '', rulings: [],
      });
      if (range) {
        prev = range.head;
        prevIsPhaseTip = false;
      }
      continue;
    }
    const unit = group.length > 1 ? batchUnit(group) : task;
    const taskBase = state === 'review' && range && prevIsPhaseTip ? range.base : prev;
    const r = state === 'review' && !range
      ? {
        task: task.id, status: 'blocked', base: prev, head: null, rounds: 0, tier_used: task.tier,
        notes: 'done but not reviewed, and no backfill commits', rulings: [],
      }
      : await runTask(m, unit, where, taskBase, io, state === 'review' ? range : null,
        unitTasks(unit).flatMap((t) => carried.get(t.id) || []).join('\n') || null);
    if (r.next_note) carry(unit, i, r.next_note);
    const finished = r.status === 'done' || r.status === 'deferred';
    if (unit === task) results.push(r);
    else if (finished) for (const t of group) results.push({ ...r, task: t.id, batch: unit.id });
    else results.push({ ...r, task: task.id, batch: unit.id });
    if (!finished) {
      io.log(`${name}: stopped at ${task.id} (${r.notes})`);
      return { results, stopped: r.notes, head: prev };
    }
    prev = r.head;
    prevIsPhaseTip = false;
  }
  return { results, stopped: null, head: prev };
}

// Run a lane's tasks in order in its worktree, the first from base (the
// feature tip the lane fast-forwards to); stop at the first task that is not
// done. Returns {lane, results, stopped:reason|null, head}.
async function runLane(m, lane, base, io = { agent, log }) {
  const r = await runTaskList(m, lane.tasks, laneWhere(m, lane), base, io, lane.name);
  return { lane: lane.id, ...r };
}

// Run lanes with at most limits.max_parallel_lanes in flight (a promise
// pool); results come back in lane order. A lane that throws stops only
// itself. base is the feature tip every lane starts from.
async function runLanes(m, lanes, base, io = { agent, log }) {
  const results = new Array(lanes.length);
  let next = 0;
  const worker = async () => {
    while (next < lanes.length) {
      const i = next;
      next += 1;
      try {
        results[i] = await runLane(m, lanes[i], base, io);
      } catch (e) {
        results[i] = { lane: lanes[i].id, results: [], stopped: `error: ${e && e.message}`, head: base };
      }
    }
  };
  const width = Math.min(m.limits.max_parallel_lanes, lanes.length);
  const workers = [];
  for (let w = 0; w < width; w += 1) workers.push(worker());
  await Promise.all(workers);
  return results;
}

// ---- Acceptance: does the delivered revision meet the run's gates ----
//
// A run that executed to the end (status complete) is not thereby accepted.
// acceptanceOf decides from the evidence alone, in code: every check that
// must hold is tied to the revision it covered, and anything missing, stale,
// failing, still open, or deferred keeps the run from being accepted.

// A finding that blocks acceptance (and a task approval).
function isBlocking(f) {
  return Boolean(f) && (f.severity === 'critical' || f.severity === 'important');
}

// Give findings stable ids in order (F1, F2, ... or another prefix), so a
// fix and its re-review talk about the same finding even when its line or
// wording changes.
function withFindingIds(findings, prefix = 'F') {
  return findings.map((f, i) => ({ ...f, id: `${prefix}${i + 1}` }));
}

// The fate of each final finding once the fixer and the re-reviewer spoke:
// fixed (the fixer fixed it and the re-review found it resolved), declined
// (the fixer declined it and the re-review agreed), or open (anything else:
// no disposition, a re-review that says open or leaves the id out, or no
// re-review at all). rr is the re-review result {results, new_findings}, or
// null when none ran (whyNot says why). New findings are open with ids N1...
function settleFinalFindings(findings, dispositions, rr, whyNot = 'not re-reviewed') {
  const said = new Map();
  for (const d of Array.isArray(dispositions) ? dispositions : []) {
    if (d && typeof d.id === 'string' && (d.status === 'fixed' || d.status === 'declined')) said.set(d.id, d);
  }
  const verdict = new Map();
  if (rr && Array.isArray(rr.results)) {
    for (const r of rr.results) if (r && typeof r.id === 'string') verdict.set(r.id, r);
  }
  const fixed = [];
  const declined = [];
  const open = [];
  for (const f of findings) {
    const d = said.get(f.id) || null;
    const v = verdict.get(f.id) || null;
    const withNotes = { ...f, disposition: d, review: v };
    if (rr === null) open.push({ ...withNotes, reason: whyNot });
    else if (!v || v.status !== 'resolved') {
      open.push({ ...withNotes, reason: v ? 'still open after the final re-review' : 'the final re-review gave no result for it' });
    } else if (d && d.status === 'declined') declined.push({ ...withNotes, reason: d.reason });
    else fixed.push(withNotes);
  }
  const fresh = rr && Array.isArray(rr.new_findings) ? withFindingIds(rr.new_findings, 'N') : [];
  for (const f of fresh) open.push({ ...f, reason: 'new in the final fix' });
  return { fixed, declined, open };
}

// The test, lint and build commands the verify step must have run, in order
// ({group, command}).
function expectedChecks(m) {
  const out = [];
  for (const group of ['test', 'lint', 'build']) for (const command of m.commands[group] || []) out.push({ group, command });
  return out;
}

// input: {m, tasks (the run report's), final, e2e ({checked_sha, items}|null),
// verify (run-checks JSON|null), post ({status, checked_sha}|null),
// delivered_sha, fix_unreviewed}. Returns {status 'accepted'|'unverified'|
// 'rejected', delivered_sha, reasons: [{kind, class 'failed'|'missing',
// detail}], warnings: [string]}. rejected: something failed or is open or
// deferred; unverified: nothing failed, but required evidence is missing or
// covers another revision.
function acceptanceOf(input) {
  const { m, tasks, final, e2e, verify, post } = input;
  const sha = input.delivered_sha;
  const reasons = [];
  const warnings = [];
  const add = (kind, cls, detail) => reasons.push({ kind, class: cls, detail });

  const deferred = new Set(m.deferred || []);
  for (const [id, t] of Object.entries(tasks)) {
    if (t.status === 'deferred' || (t.status === 'skipped' && deferred.has(id))) {
      add('deferred_task', 'failed', `task ${id} was deferred by the adjudicator, not delivered: ${t.notes || 'see the ledger'}`);
    } else if (t.status !== 'done' && t.status !== 'skipped') {
      add('task_not_done', 'failed', `task ${id} is ${t.status}`);
    }
  }

  const want = expectedChecks(m);
  if (want.length === 0) {
    warnings.push('no test, lint or build command is configured, so no check ran at the delivered revision');
  } else if (!verify || !Array.isArray(verify.results)) {
    add('checks_missing', 'missing', 'the project checks did not run at the delivered revision');
  } else if (verify.head !== sha) {
    add('checks_stale', 'missing', `the project checks ran at ${verify.head}, not at the delivered ${sha}`);
  } else if (verify.results.length !== want.length
    || want.some((w, i) => verify.results[i].group !== w.group || verify.results[i].command !== w.command)) {
    add('checks_incomplete', 'missing', 'the verify step did not run exactly the configured test, lint and build commands');
  } else if (verify.ok !== true || verify.results.some((r) => r.exit !== 0)) {
    const failed = verify.results.filter((r) => r.exit !== 0).map((r) => `${r.command} (exit ${r.exit})`);
    add('checks_failed', 'failed', failed.length > 0 ? `failing at ${sha}: ${failed.join(', ')}` : `checks reported not ok at ${sha}`);
  }

  if (m.hooks.e2e) {
    if (!e2e || !Array.isArray(e2e.items) || e2e.items.length === 0) {
      add('e2e_missing', 'missing', 'the end-to-end check returned no items');
    } else if (e2e.checked_sha !== sha) {
      add('e2e_stale', 'missing', `the end-to-end check covered ${e2e.checked_sha || 'an unknown revision'}, not ${sha}`);
    } else {
      const failed = e2e.items.filter((i) => i.result !== 'PASS');
      if (failed.length > 0) add('e2e_failed', 'failed', `end-to-end FAIL at ${sha}: ${failed.map((i) => i.item).join(', ')}`);
    }
  }

  if (m.hooks.post_integrate && m.profile !== 'lite') {
    if (!post) add('post_integrate_missing', 'missing', 'the post-integration check did not run at the delivered revision');
    else if (post.checked_sha !== sha) {
      add('post_integrate_stale', 'missing', `the post-integration check covered ${post.checked_sha || 'an unknown revision'}, not ${sha}`);
    } else if (post.status !== 'done') add('post_integrate_failed', 'failed', `post-integration check failed: ${post.notes}`);
  }

  if (input.fix_unreviewed) add('fix_unreviewed', 'missing', 'a post-integration fix was not re-reviewed');
  if (final) {
    for (const lens of final.missing_lenses || []) add('review_missing', 'missing', `the ${lens} final review returned no result`);
    const open = final.open || [];
    const blocking = open.filter(isBlocking);
    if (blocking.length > 0) {
      add('blocking_findings', 'failed', blocking.map((f) => `${f.id} [${f.severity}] ${f.file}:${f.line} ${f.issue} (${f.reason})`).join('; '));
    }
    for (const f of open.filter((x) => !isBlocking(x))) warnings.push(`open minor finding ${f.id}: ${f.file}:${f.line} ${f.issue}`);
    for (const item of final.cannot_verify || []) warnings.push(`cannot verify: ${item}`);
  } else {
    add('review_missing', 'missing', 'the final review did not run');
  }

  const status = reasons.some((r) => r.class === 'failed') ? 'rejected'
    : reasons.length > 0 ? 'unverified' : 'accepted';
  return { status, delivered_sha: sha, reasons, warnings };
}

// ---- Run phases: setup, pre-flight, integration, E2E, final review ----
//
// Phase agents act on the repo only through git commands named in their
// prompts; the script itself never touches files or runs commands.

// Final review: three lenses in parallel (profile lite: one combined
// reviewer labelled `final review`), one fix agent, one re-review of every
// finding. tip is the real feature head: the first head a reviewer reported,
// else base (the feature tip the script tracked); on a resume after an
// earlier final fix the two differ. carried holds findings from before the
// final review (the post-integrate re-reviews, C2): they join the lenses'
// findings, so the one fix wave and the re-review cover them too.
// Findings get stable ids (F1...) before the fix; the fixer returns a
// disposition per id and the re-review a result per id, so a finding whose
// line or wording changes is still the same finding, and a declined finding
// is judged by the re-reviewer, not just by the fixer. The re-review runs
// whenever there are findings and a fix result, even without fix commits
// (declines still need judging). Returns {findings, fixed, declined, open,
// cannot_verify, missing_lenses, head}: head is the delivered feature head
// (the fix head when the fix committed), open lists every finding not fixed
// and not rightly declined, each with a reason.
async function runFinalReview(m, e2e, base, io, carried = []) {
  const standard = tierSettings('standard');
  const call = (label, prompt, schema) =>
    io.agent(prompt, { label, phase: 'Final review', schema, ...standard });
  // [label, lens name for findings and cannot_verify, prompt]
  const lenses = m.profile === 'lite'
    ? [['final review', 'combined', combinedFinalReviewPrompt(m, { e2e })]]
    : [['sp', 'superpowers'], ['security', 'security'], ['correctness', 'correctness']]
      .map(([key, name]) => [`final review ${key}`, name, finalReviewPrompt(m, key, e2e)]);
  const results = await io.parallel(lenses.map(([label, , prompt]) => () =>
    call(label, prompt, finalReviewSchema())));
  const cannotVerify = [];
  const missing = [];
  lenses.forEach(([, name], i) => {
    const r = results[i];
    if (!r || !Array.isArray(r.findings)) missing.push(name);
    else for (const item of r.cannot_verify || []) cannotVerify.push(`${name}: ${item}`);
  });
  const findings = withFindingIds(dedupeFindings([
    ...lenses.map(([, name], i) => ({ lens: name, findings: results[i] ? results[i].findings : null })),
    { lens: 'post-integrate re-review', findings: carried },
  ]));
  const lensHead = results.find((r) => r && present(r.head));
  const tip = lensHead ? lensHead.head : base;
  const final = {
    findings, fixed: [], declined: [], open: [], cannot_verify: cannotVerify, missing_lenses: missing, head: tip,
  };
  if (findings.length === 0) return final;
  const settle = (dispositions, rr, why) => Object.assign(final, settleFinalFindings(findings, dispositions, rr, why));

  // Final fix tier (spec decision 5): Sonnet when every finding is minor or
  // every finding is in documentation; otherwise Opus. A Sonnet fix that does
  // not finish reruns once on Opus (same label); still one fix wave.
  const docsOnly = findings.every((f) => typeof f.file === 'string' && f.file.endsWith('.md'));
  const minorOnly = findings.every((f) => f.severity === 'minor');
  const fixSettings = minorOnly || docsOnly ? { model: 'sonnet', effort: 'high' } : standard;
  const callFix = (settings) => io.agent(finalFixPrompt(m, findings, tip),
    { label: 'final fix', phase: 'Final review', schema: finalFixSchema(), ...settings });
  let fix = await callFix(fixSettings);
  if (fixSettings.model === 'sonnet' && (!fix || fix.status !== 'done')) fix = await callFix(standard);
  // Whatever the fix agent did, commits it reports are delivered code.
  if (fix && present(fix.head)) final.head = fix.head;
  if (!fix || fix.__budget) return settle([], null, fix ? 'final fix not run: budget exhausted' : 'no result from final fix');
  if (fix.status !== 'done') return settle([], null, `final fix blocked: ${fix.notes}`);
  const dispositions = Array.isArray(fix.dispositions) ? fix.dispositions : [];
  const verifying = findings.map((f) => ({ ...f, disposition: dispositions.find((d) => d && d.id === f.id) || null }));
  const rr = await call('final re-review', finalReReviewPrompt(m, tip, final.head, verifying), finalReReviewSchema());
  // A refused re-review returns the budget sentinel, which has no results.
  if (!rr || !Array.isArray(rr.results)) {
    return settle(dispositions, null, rr && rr.__budget ? 'final re-review not run: budget exhausted'
      : 'no result from final re-review');
  }
  return settle(dispositions, rr);
}

// setup_result (scripts/setup) must name, for every lane, the worktree the
// run uses for it: its lane worktree, or the feature checkout under profile
// lite. The script cannot stat paths; scripts/setup guarantees they exist.
// Returns error strings naming each lane that is missing or different.
function setupResultErrors(m) {
  if (!m.setup_result) return [];
  const errors = [];
  for (const lane of m.lanes) {
    const want = m.profile === 'lite' ? featureDir(m) : laneWhere(m, lane).dir;
    const got = m.setup_result.worktrees[lane.id];
    if (got === undefined) {
      errors.push(`setup_result.worktrees: missing a worktree for lane ${lane.id}`);
    } else if (got !== want) {
      errors.push(`setup_result.worktrees.${lane.id}: ${got} is not the worktree the run uses for lane ${lane.id} (${want})`);
    }
  }
  return errors;
}

// The last commit of each lane, {<lane id>: sha}: the head its lane run
// reported, else (a lane with nothing left to run) the backfill head of its
// last done task. A lane with neither is left out.
function laneTips(m, laneResults) {
  const backfill = m.backfill || {};
  const tips = {};
  for (const lane of m.lanes) {
    const lr = laneResults.find((r) => r.lane === lane.id);
    if (lr && present(lr.head)) {
      tips[lane.id] = lr.head;
      continue;
    }
    for (const t of lane.tasks) if (backfill[t.id]) tips[lane.id] = backfill[t.id].head;
  }
  return tips;
}

// The ids of the tasks an agent label belongs to: `<id> <role>`, or a batch
// `<first>-<last> <role>` covering first through last in plan order. Phase
// labels (setup, integrate, final review, ...) belong to no task.
function labelTasks(m, label) {
  const ids = [...m.prelude, ...m.lanes.flatMap((l) => l.tasks), ...m.join].map((t) => t.id);
  const head = label.split(' ')[0];
  if (ids.includes(head)) return [head];
  for (let i = 0; i < ids.length; i += 1) {
    for (let j = i + 1; j < ids.length; j += 1) {
      if (head === `${ids[i]}-${ids[j]}`) return ids.slice(i, j + 1);
    }
  }
  return [];
}

// A copy of the manifest whose notes for every not-yet-done task gain the
// pre-flight ruling (spec C1). taskContext shows a task's note, so the ruling
// binds every task agent for this run without an engine change.
function preflightResolved(m, text) {
  const line = `Pre-flight ruling (binding for this run): ${text}`;
  const notes = { ...(m.notes || {}) };
  const done = new Set(m.done);
  for (const t of [...m.prelude, ...m.lanes.flatMap((l) => l.tasks), ...m.join]) {
    if (done.has(t.id)) continue;
    notes[t.id] = notes[t.id] ? `${notes[t.id]}\n${line}` : line;
  }
  return { ...m, notes };
}

// A copy of the manifest whose notes carry the unblock note of each result
// (next_note) to the tasks of later whose depends_on names its task: later
// is the lanes and the join after the prelude, the join after the lanes (a
// list's own dependents get the note from runTaskList; lanes run at once, so
// a lane-to-lane note is not carried).
function withCarriedNotes(m, results, later) {
  const unblocked = results.filter((r) => present(r.next_note));
  if (unblocked.length === 0) return m;
  const notes = { ...(m.notes || {}) };
  for (const t of later) {
    for (const r of unblocked) {
      if (!(t.depends_on || []).some((d) => d.id === r.task)) continue;
      const line = `from ${r.task}, unblocked by the adjudicator: ${r.next_note}`;
      if (notes[t.id] && notes[t.id].includes(line)) continue;
      notes[t.id] = notes[t.id] ? `${notes[t.id]}\n${line}` : line;
    }
  }
  return { ...m, notes };
}

// The undeclared dependencies pre-flight reported, split into the entries
// the run keeps and the ones it drops with a reason: an entry must be an
// object with string task, producer and what, name two different task ids of
// the manifest, and name a task that is not done and reviewed (a done task
// still to review keeps its entry: its reviewer and fix agents use it).
function preflightUndeclared(m, entries) {
  const ids = new Set([...m.prelude, ...m.lanes.flatMap((l) => l.tasks), ...m.join].map((t) => t.id));
  const kept = [];
  const dropped = [];
  for (const entry of Array.isArray(entries) ? entries : []) {
    const drop = (reason) => dropped.push({ entry, reason });
    const shaped = entry !== null && typeof entry === 'object' && !Array.isArray(entry) &&
      ['task', 'producer', 'what'].every((k) => typeof entry[k] === 'string');
    if (!shaped) drop('not an object with string task, producer and what');
    else if (!ids.has(entry.task)) drop(`task ${entry.task} is not in the run`);
    else if (!ids.has(entry.producer)) drop(`producer ${entry.producer} is not in the run`);
    else if (entry.task === entry.producer) drop('task and producer are the same');
    else if (taskState(m, entry.task) === 'skip') drop(`task ${entry.task} is already done and reviewed`);
    else kept.push({ task: entry.task, producer: entry.producer, what: entry.what });
  }
  return { kept, dropped };
}

// A copy of the manifest with consumes_extra: {<task>: [<producer>, ...]}
// from the kept undeclared entries, producers in entry order without
// duplicates. startCommand and the adjudicator's task-brief command pass
// them as --also, so each producer's Produces block reaches the task's
// briefs for this run (the manifest file is not changed).
function withConsumesExtra(m, kept) {
  const extra = {};
  for (const e of kept) {
    const list = extra[e.task] || (extra[e.task] = []);
    if (!list.includes(e.producer)) list.push(e.producer);
  }
  return { ...m, consumes_extra: extra };
}

// The whole run. io = {agent, log, phase, parallel}. Returns the report:
// {status:'complete'|'stopped'|'preflight_conflicts'|'invalid', run_id,
//  tasks:{<id>:{status, rounds, tier_used, commits:[base,head]|null, notes}},
//  stopped_lanes:[{lane, task, reason}], preflight:{conflicts, rulings, undeclared},
//  integrate:{status, notes, post_integrate, fix_review}, e2e:{items, checked_sha}|null,
//  final:{findings, fixed, declined, open, cannot_verify, missing_lenses, head},
//  verify (the run-checks result at the delivered revision)|null,
//  delivered_sha, acceptance:{status, delivered_sha, reasons, warnings}|null
//  (complete runs only: status complete says the run executed to the end,
//  acceptance says whether the delivered revision meets the gates;
//  acceptanceOf), agents_spawned,
//  rulings_spent (adjudications that ran; a relaunch subtracts it from
//  limits.max_rulings), reason (stopped runs only), errors (invalid only),
//  budget:{agents, rulings, limits} (reason budget only),
//  agent_type_fallback: true (only when a failing agent_type switched the
//  rest of the run to the default agent type; see makeIo)}.
// integrate.fix_review lists the findings of the post-integrate re-reviews
// (C2); they also reach the final fix wave. Task status is done, deferred
// (parked or unblocked by the adjudicator: never accepted), blocked, skipped
// (done and reviewed earlier), or not_run. Under profile lite no
// pre-flight agent runs (preflight has no conflicts, rulings or undeclared
// entries) and integrate stays null (validateManifest rejects lite with a
// post_integrate hook, so no configured hook is skipped).
async function runAll(m, io) {
  let errors = validateManifest(m);
  if (errors.length === 0) errors = setupResultErrors(m);
  if (errors.length > 0) {
    const runId = m !== null && typeof m === 'object' && typeof m.run_id === 'string' ? m.run_id : null;
    return {
      status: 'invalid', run_id: runId, errors, tasks: {}, stopped_lanes: [], preflight: null,
      integrate: null, e2e: null, final: null, verify: null, delivered_sha: null, acceptance: null,
      agents_spawned: 0, rulings_spent: 0,
    };
  }

  // Every agent of the run spawns through the budget wrapper (budget.js).
  const state = { agents: 0, rulings: 0, refused: [] };
  const counted = makeIo(m, io, state);
  const standard = tierSettings('standard');
  const sonnetHigh = { model: 'sonnet', effort: 'high' };
  const call = (label, phaseName, prompt, schema) =>
    counted.agent(prompt, { label, phase: phaseName, schema, ...standard });
  const callM = (label, phaseName, prompt, schema, settings) =>
    counted.agent(prompt, { label, phase: phaseName, schema, ...settings });
  const autonomous = effectiveAutonomy(m) === 'autonomous';

  const tasks = {};
  const deferredBefore = new Set(m.deferred || []);
  for (const t of [...m.prelude, ...m.lanes.flatMap((l) => l.tasks), ...m.join]) {
    const range = taskState(m, t.id) === 'skip' ? (m.backfill || {})[t.id] : null;
    tasks[t.id] = {
      status: taskState(m, t.id) === 'skip' ? (deferredBefore.has(t.id) ? 'deferred' : 'skipped') : 'not_run',
      rounds: null,
      tier_used: null,
      commits: range ? [range.base, range.head] : null,
      notes: '',
    };
  }
  const record = (results) => {
    for (const r of results) {
      tasks[r.task] = {
        // A task the ledger lists as deferred stays deferred when skipped.
        status: r.status === 'skipped' && deferredBefore.has(r.task) ? 'deferred' : r.status,
        rounds: r.rounds,
        tier_used: r.tier_used,
        commits: present(r.base) && present(r.head) ? [r.base, r.head] : null,
        notes: r.notes,
      };
    }
  };
  const stoppedLanes = [];
  const stopAt = (lane, list) => {
    const last = list.results[list.results.length - 1];
    stoppedLanes.push({ lane, task: last && last.status !== 'done' ? last.task : null, reason: list.stopped });
  };
  let preflight = null;
  let integrate = null;
  let e2e = null;
  let final = null;
  let verify = null;
  let post = null;
  let delivered = null;
  let acceptance = null;
  // Set when a post-integrate fix's re-review returned no result (C2).
  let fixUnreviewed = false;
  // The post-integrate check's result and the revision it covered.
  let postCheck = null;
  const report = (status, reason = null) => ({
    status,
    run_id: m.run_id,
    tasks,
    stopped_lanes: stoppedLanes,
    preflight,
    integrate,
    e2e,
    final,
    verify,
    delivered_sha: delivered,
    acceptance,
    agents_spawned: state.agents,
    rulings_spent: state.rulings,
    ...(reason === null ? {} : { reason }),
    ...(reason === 'budget'
      ? { budget: { agents: state.agents, rulings: state.rulings, limits: effectiveLimits(m) } }
      : {}),
    ...(state.untyped ? { agent_type_fallback: true } : {}),
  });
  // The run stops (resumable) once an agent was refused: runAll checks
  // state.refused after every phase step, ahead of any other stop reason.
  // Each task whose agent was refused says so in its notes.
  const budgetReport = () => {
    const notes = new Map();
    for (const label of state.refused) {
      for (const id of labelTasks(m, label)) {
        notes.set(id, [...(notes.get(id) || []), `budget exhausted: ${label} was not run`]);
      }
    }
    for (const [id, lines] of notes) {
      const t = tasks[id];
      const text = lines.join('\n');
      t.notes = t.status === 'done' && t.notes ? `${t.notes}\n${text}` : text;
    }
    return report('stopped', 'budget');
  };

  const planned = planAgents(m);
  if (m.done.length > 0) {
    io.log(`parallel-lanes: resuming run ${m.run_id}: ${m.done.length} tasks already committed`);
  } else {
    const lanesWithWork = new Set(planned.filter((a) => a.lane !== null).map((a) => a.lane)).size;
    io.log(`parallel-lanes: launching run ${m.run_id}: ${lanesWithWork} lanes, ${planned.length} agents`);
  }

  // Setup: the session ran scripts/setup and passed its output (the only
  // setup; validateManifest requires it for a launch).
  const setup = m.setup_result;
  for (const item of setup.discarded || []) io.log(`parallel-lanes: discarded uncommitted change ${item}`);
  for (const p of setup.preserved || []) {
    io.log(`parallel-lanes: saved the discarded changes of ${p.worktree} as ${p.ref} (${p.commit})`);
  }
  if (!present(setup.feature_head)) return report('stopped', 'setup failed: no feature head reported');
  // The feature tip: the base of the next task on the feature branch.
  let tip = setup.feature_head;
  // Saved start points (ledger run_started events) replace the phase tip
  // only as the base of the prelude and join lists, so commits an earlier
  // attempt made at a first task before recording it are reviewed too. A
  // list that moved no head leaves the tip where the phase put it.
  const starts = m.start_points || {};
  const moved = (list) => list.results.some((r) => present(r.head));
  const listTip = (list) => (moved(list) ? list.head : tip);

  // Profile lite (spec D2): validateManifest above is the whole pre-flight;
  // the single lane runs on the feature branch, so there is no integration.
  const lite = m.profile === 'lite';
  if (lite) {
    preflight = { conflicts: [], rulings: [], undeclared: [] };
  } else {
    io.phase('Pre-flight');
    const pre = await call('pre-flight', 'Pre-flight', preflightPrompt(m), preflightSchema());
    if (state.refused.length > 0) return budgetReport();
    if (!pre) return report('stopped', 'no result from pre-flight');
    // Undeclared dependencies only add context: they reach the briefs of
    // their task and never stop the run or call the adjudicator.
    const { kept, dropped } = preflightUndeclared(m, pre.undeclared);
    for (const d of dropped) {
      io.log(`parallel-lanes: pre-flight: dropped undeclared entry ${JSON.stringify(d.entry)} (${d.reason})`);
    }
    for (const e of kept) io.log(`parallel-lanes: pre-flight: ${e.task} also consumes ${e.producer} (${e.what})`);
    preflight = { conflicts: pre.conflicts, rulings: [...pre.rulings], undeclared: kept };
    m = withConsumesExtra(m, kept);
    if (pre.conflicts.length > 0) {
      // Supervised keeps Plan 1 (stop and wait); autonomous adjudicates (C1).
      if (!autonomous) return report('preflight_conflicts');
      const ruling = await adjudicate(m,
        { kind: 'preflight', task: null, where: null, details: pre.conflicts.join('\n'), findings: [] }, counted);
      if (state.refused.length > 0) return budgetReport();
      if (ruling.outcome === 'stop') {
        // An unavailable adjudicator (agent error) stops the run; a real stop
        // decision is a pre-flight conflict the user settles.
        if (ruling.unavailable) return report('stopped', ruling.text);
        return report('preflight_conflicts');
      }
      // The ruling binds every not-yet-done task: taskContext shows each
      // task's note, so the ruling reaches every task agent.
      preflight.rulings.push(ruling.text);
      m = preflightResolved(m, ruling.text);
    }
  }

  io.phase('Prelude');
  const prelude = await runTaskList(m, m.prelude, featureWhere(m, 'prelude'), starts.prelude || tip,
    counted, 'Prelude', true);
  record(prelude.results);
  m = withCarriedNotes(m, prelude.results, [...m.lanes.flatMap((l) => l.tasks), ...m.join]);
  if (prelude.stopped !== null) stopAt('prelude', prelude);
  if (state.refused.length > 0) return budgetReport();
  if (prelude.stopped !== null) return report('stopped', 'prelude stopped');
  tip = listTip(prelude);

  // The join's base, and whether it is a phase tip (P1: a backfilled first
  // task then reviews its own recorded range).
  let joinBase;
  let joinFromPhase = true;
  if (lite) {
    // The single lane continues the prelude on the feature branch: no lane
    // worktree, no sync, no integration. When the prelude moved no head the
    // lane's base is a phase tip (the saved setup start point if any), as
    // for the prelude itself. The join starts at the lane's last head; lite
    // records no join start point.
    const lane = m.lanes[0];
    const fromPhase = !moved(prelude);
    const list = await runTaskList(m, lane.tasks, featureWhere(m, lane.id),
      fromPhase ? starts.prelude || tip : tip, counted, lane.name, fromPhase);
    record(list.results);
    m = withCarriedNotes(m, list.results, m.join);
    if (list.stopped !== null) stopAt(lane.id, list);
    if (state.refused.length > 0) return budgetReport();
    if (list.stopped !== null) return report('stopped', 'lanes stopped');
    tip = listTip(list);
    joinBase = tip;
    joinFromPhase = fromPhase && !moved(list);
  } else {
    // Lane agents carry their lane's phase; lanes with nothing left are skipped.
    const laneResults = await runLanes(m, m.lanes.filter((l) => hasWork(m, l.tasks)), tip, counted);
    for (const lr of laneResults) {
      record(lr.results);
      m = withCarriedNotes(m, lr.results, m.join);
      if (lr.stopped !== null) stopAt(lr.lane, lr);
    }
    if (state.refused.length > 0) return budgetReport();
    if (stoppedLanes.length > 0) return report('stopped', 'lanes stopped');

    io.phase('Integrate');
    // A phase result that is done must also report the head it left.
    const phaseResult = (r, label) => {
      if (!r) return { status: 'failed', notes: `no result from ${label}` };
      if (r.status === 'done' && !present(r.head)) return { status: 'failed', notes: `${label} reported no head` };
      return { status: r.status, notes: r.notes };
    };
    const preludeTip = tip;
    const BUDGET = Symbol('budget');
    // Post-integrate re-review findings (C2): reported under
    // integrate.fix_review and carried into the final fix wave.
    const fixReview = [];
    const integrateReport = (r) => ({ ...phaseResult(r, 'integrate'), post_integrate: null, fix_review: fixReview });
    // The Opus fix + scoped re-review (C2) for a post-integration failure.
    // Returns the head to rerun from (base when the fix made no commit), or
    // BUDGET when a spawn was refused.
    const fixPostIntegration = async (failureNotes, base) => {
      const fix = await callM('post-integrate fix', 'Integrate',
        postIntegrateFixPrompt(m, failureNotes), statusSchema(), standard);
      if (state.refused.length > 0) return BUDGET;
      if (fix && fix.status === 'done' && present(fix.head) && fix.head !== base) {
        const rr = await callM('post-integrate re-review', 'Integrate',
          postIntegrateReReviewPrompt(m, base, fix.head), postIntegrateReReviewSchema(), standard);
        if (state.refused.length > 0) return BUDGET;
        if (rr && Array.isArray(rr.findings)) fixReview.push(...rr.findings);
        else fixUnreviewed = true;
        return fix.head;
      }
      return base;
    };
    // Integrate starts on Sonnet with a prompt that never resolves conflicts
    // (D5). A conflict or any other failure escalates to an Opus rerun; in
    // autonomous mode a conflict first goes to an Opus resolver (C2).
    const joinNoHook = !m.hooks.post_integrate;
    // Each lane's last commit: a rerun counts a lane branch an earlier
    // cleanup deleted as merged when that commit is already in HEAD.
    const tips = laneTips(m, laneResults);
    let integ = await callM('integrate', 'Integrate',
      integratePrompt(m, preludeTip, { conflictMode: 'abort', joinStartPoint: joinNoHook, laneTips: tips }),
      statusSchema(), sonnetHigh);
    if (state.refused.length > 0) return budgetReport();
    // Any Sonnet result that is not a finished integration (a done without a
    // head included) escalates.
    if (phaseResult(integ, 'integrate').status !== 'done') {
      const conflicts = integ && Array.isArray(integ.conflict_files) ? integ.conflict_files : [];
      // The rerun reviews a resolution only when the resolver finished it;
      // otherwise it resolves the conflicts itself on the plain prompt.
      let resolved = null;
      if (conflicts.length > 0 && autonomous) {
        const res = await callM('resolve conflicts', 'Integrate',
          resolveConflictsPrompt(m, preludeTip, conflicts), statusSchema(), standard);
        if (state.refused.length > 0) return budgetReport();
        if (res && res.status === 'done' && present(res.head)) resolved = { files: conflicts, notes: res.notes };
      }
      // Every Sonnet failure or null escalates to one Opus rerun (D5).
      // Autonomous heals a residual command failure into tests_failed;
      // supervised uses the Plan 1 prompt (resolve only with confidence,
      // fail on a command failure) and stops if the rerun fails.
      integ = await callM('integrate', 'Integrate',
        integratePrompt(m, preludeTip, {
          testFailure: autonomous ? 'heal' : 'fail',
          reviewConflicts: resolved ? resolved.files : null,
          resolverNotes: resolved ? resolved.notes : null,
          joinStartPoint: joinNoHook,
          laneTips: tips,
        }), statusSchema(), standard);
      if (state.refused.length > 0) return budgetReport();
    }
    integrate = integrateReport(integ);
    if (integrate.status !== 'done') return report('stopped', `integration failed: ${integrate.notes}`);
    tip = integ.head;
    // Post-integration test failures (autonomous, C2): fix + re-review, then
    // rerun the integrate step once; still failing stops the run.
    if (autonomous && integ.tests_failed === true) {
      const from = await fixPostIntegration(integrate.notes || 'a project command failed after the merges', tip);
      if (from === BUDGET) return budgetReport();
      tip = from;
      integ = await callM('integrate', 'Integrate',
        integratePrompt(m, preludeTip, { testFailure: 'heal', joinStartPoint: joinNoHook, laneTips: tips }),
        statusSchema(), standard);
      if (state.refused.length > 0) return budgetReport();
      integrate = integrateReport(integ);
      if (integrate.status !== 'done' || integ.tests_failed === true) {
        return report('stopped', `integration failed: ${integrate.notes || 'tests still failing after the fix'}`);
      }
      tip = integ.head;
    }
    if (m.hooks.post_integrate) {
      let post = await call('post-integrate', 'Integrate', postIntegratePrompt(m), statusSchema());
      if (state.refused.length > 0) return budgetReport();
      let pr = phaseResult(post, 'post-integrate');
      // Autonomous self-heal (C2): fix + re-review, then rerun the hook once.
      if (autonomous && pr.status !== 'done') {
        const from = await fixPostIntegration(pr.notes, tip);
        if (from === BUDGET) return budgetReport();
        tip = from;
        post = await call('post-integrate', 'Integrate', postIntegratePrompt(m), statusSchema());
        if (state.refused.length > 0) return budgetReport();
        pr = phaseResult(post, 'post-integrate');
      }
      integrate.post_integrate = pr;
      if (pr.status !== 'done') return report('stopped', `post-integrate failed: ${pr.notes}`);
      tip = post.head;
      // The revision the check covered: a later commit makes it stale.
      postCheck = { status: pr.status, notes: pr.notes, checked_sha: post.head };
    }
    joinBase = starts.join || tip;
  }

  io.phase('Join');
  const join = await runTaskList(m, m.join, featureWhere(m, 'join'), joinBase,
    counted, 'Join', joinFromPhase);
  record(join.results);
  if (join.stopped !== null) stopAt('join', join);
  if (state.refused.length > 0) return budgetReport();
  if (join.stopped !== null) return report('stopped', 'join stopped');
  tip = listTip(join);

  // E2E runs on Sonnet first (D5); a null result or any FAIL reruns it on
  // Opus (same label) and the Opus result is used. It records the revision
  // its checks covered.
  const runE2e = async (label, phaseName) => {
    let r = await callM(label, phaseName, e2ePrompt(m), e2eSchema(), sonnetHigh);
    if (state.refused.length > 0) return null;
    if (!r || (r.items || []).some((i) => i.result === 'FAIL')) {
      r = await callM(label, phaseName, e2ePrompt(m), e2eSchema(), standard);
      if (state.refused.length > 0) return null;
    }
    return r && Array.isArray(r.items) ? { items: r.items, checked_sha: present(r.head) ? r.head : null }
      : { items: [], checked_sha: null, notes: `no result from ${label}` };
  };
  if (m.hooks.e2e) {
    io.phase('E2E');
    e2e = await runE2e('e2e', 'E2E');
    if (state.refused.length > 0) return budgetReport();
  }

  io.phase('Final review');
  final = await runFinalReview(m, e2e, tip, counted, integrate ? integrate.fix_review : []);
  if (state.refused.length > 0) return budgetReport();
  if (e2e !== null && e2e.notes) final.cannot_verify.unshift('the e2e check returned no result');
  if (fixUnreviewed) final.cannot_verify.unshift('the post-integrate re-review returned no result');
  delivered = final.head;

  // Verify: the evidence acceptance rests on, at the delivered revision.
  // The project checks always run there (scripts/run-checks); the e2e and
  // post-integrate checks rerun only when a later commit made their evidence
  // stale (the post-integrate one check-only).
  io.phase('Verify');
  if (checksCommand(m, null, featureDir(m)) !== null) {
    verify = await callM('verify', 'Verify', verifyPrompt(m, delivered), verifySchema(), sonnetHigh);
    if (state.refused.length > 0) return budgetReport();
  }
  if (m.hooks.e2e && (!e2e || e2e.checked_sha !== delivered)) {
    e2e = await runE2e('e2e recheck', 'Verify');
    if (state.refused.length > 0) return budgetReport();
  }
  if (m.hooks.post_integrate && !lite && (!postCheck || postCheck.checked_sha !== delivered)) {
    const r = await call('post-integrate recheck', 'Verify', postIntegratePrompt(m, true), statusSchema());
    if (state.refused.length > 0) return budgetReport();
    const pr = phaseCheck(r, 'post-integrate recheck');
    postCheck = { ...pr, checked_sha: r && present(r.head) ? r.head : null };
    if (postCheck.checked_sha !== null && postCheck.checked_sha !== delivered) {
      postCheck = { status: 'failed', notes: `the recheck left HEAD at ${postCheck.checked_sha}`, checked_sha: delivered };
    }
  }
  post = postCheck;
  acceptance = acceptanceOf({
    m, tasks, final, e2e, verify, post, delivered_sha: delivered, fix_unreviewed: fixUnreviewed,
  });
  io.log(`parallel-lanes: acceptance ${acceptance.status} at ${delivered}`
    + (acceptance.reasons.length > 0 ? `: ${acceptance.reasons.map((r) => r.kind).join(', ')}` : ''));
  return report('complete');
}

// A phase agent's status result as {status, notes}: done only with a head.
function phaseCheck(r, label) {
  if (!r) return { status: 'failed', notes: `no result from ${label}` };
  if (r.status === 'done' && !present(r.head)) return { status: 'failed', notes: `${label} reported no head` };
  return { status: r.status, notes: r.notes };
}

